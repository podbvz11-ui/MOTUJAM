# ---------- 화면 배치도 (1920x1080 을 1/2 로 줄여 그림) ----------
def box(x, y, w, h, label, cls='b'):
    """x, y 는 게임 좌표(가운데가 0,0, 위가 +). w, h 는 크기."""
    sx, sy = (960 + x - w / 2) / 2, (540 - y - h / 2) / 2
    lines = label.split('|')
    ty = sy + h / 4 - (len(lines) - 1) * 6 + 4
    text = ''.join('<text x="%.0f" y="%.0f" text-anchor="middle">%s</text>' % (sx + w / 4, ty + i * 13, html.escape(l)) for i, l in enumerate(lines))
    return '<rect class="%s" x="%.0f" y="%.0f" width="%.0f" height="%.0f"/>%s' % (cls, sx, sy, w / 2, h / 2, text)

